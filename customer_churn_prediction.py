# ------------------------------

new_data = {}

# -------- Binary features (0/1) --------
binary_features = {
    "gender": "male=0, female=1",
    "SeniorCitizen": "yes=1, no=0",
    "Partner": "yes=1, no=0",
    "Dependents": "yes=1, no=0",
    "PhoneService": "yes=1, no=0",
    "MultipleLines": "yes=1, no=0",
    "OnlineSecurity": "yes=1, no=0",
    "OnlineBackup": "yes=1, no=0",
    "DeviceProtection": "yes=1, no=0",
    "TechSupport": "yes=1, no=0",
    "StreamingTV": "yes=1, no=0",
    "StreamingMovies": "yes=1, no=0",
    "PaperlessBilling": "yes=1, no=0"
}

for feature, meaning in binary_features.items():
    while True:
        try:
            val = int(input(f"Enter {feature} ({meaning}): "))
            if val in [0, 1]:
                new_data[feature] = [val]
                break
            else:
                print("Invalid input! Enter 0 or 1 only.")
        except:
            print("Invalid input! Enter 0 or 1 only.")

# -------- Categorical features with limited options --------
# Contract (month-to-month=0, one year=1, two year=2)
while True:
    try:
        val = int(input("Enter Contract (month-to-month=0, one year=1, two year=2): "))
        if val in [0, 1, 2]:
            new_data['Contract'] = [val]
            break
        else:
            print("Invalid input! Enter 0, 1, or 2 only.")
    except:
        print("Invalid input! Enter 0, 1, or 2 only.")

# InternetService (DSL=0, Fiber optic=1, No=2)
while True:
    try:
        val = int(input("Enter InternetService (DSL=0, Fiber optic=1, No=2): "))
        if val in [0, 1, 2]:
            new_data['InternetService'] = [val]
            break
        else:
            print("Invalid input! Enter 0, 1, or 2 only.")
    except:
        print("Invalid input! Enter 0, 1, or 2 only.")

# PaymentMethod (electronic check=0, mailed check=1, bank transfer=2, credit card=3)
while True:
    try:
        val = int(input("Enter PaymentMethod (electronic check=0, mailed check=1, bank transfer=2, credit card=3): "))
        if val in [0, 1, 2, 3]:
            new_data['PaymentMethod'] = [val]
            break
        else:
            print("Invalid input! Enter 0, 1, 2, or 3 only.")
    except:
        print("Invalid input! Enter 0, 1, 2, or 3 only.")

# -------- Numeric features --------
while True:
    try:
        val = int(input("Enter tenure (int, 0-72 months): "))
        if 0 <= val <= 72:
            new_data['tenure'] = [val]
            break
        else:
            print("Enter a number between 0 and 72.")
    except:
        print("Invalid input! Enter an integer between 0 and 72.")

while True:
    try:
        val = float(input("Enter MonthlyCharges (float, 0-500): "))
        if 0 <= val <= 500:
            new_data['MonthlyCharges'] = [val]
            break
        else:
            print("Enter a number between 0 and 500.")
    except:
        print("Invalid input! Enter a valid number.")

while True:
    try:
        val = float(input("Enter TotalCharges (float, 0-5000): "))
        if 0 <= val <= 5000:
            new_data['TotalCharges'] = [val]
            break
        else:
            print("Enter a number between 0 and 5000.")
    except:
        print("Invalid input! Enter a valid number.")

# -------- Convert to DataFrame & predict --------
new_customer = pd.DataFrame(new_data)
new_customer = new_customer[X.columns]  # preserve column order
new_customer_scaled = scaler.transform(new_customer)
prediction = rf.predict(new_customer_scaled)

print("Churn Prediction:", "Yes" if prediction[0] == 1 else "No")
